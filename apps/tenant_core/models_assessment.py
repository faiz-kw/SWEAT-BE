import uuid
from django.db import models
from .models_org import Organization, Branch
from .models_crm import UserProfile


class MemberAssessment(models.Model):
    """
    Physical Assessment / Body Composition Scan Session.
    Managed = False placeholder until migrations are formally generated by assessment team.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(Organization, on_delete=models.CASCADE, related_name='assessments')
    branch = models.ForeignKey(Branch, on_delete=models.CASCADE, related_name='assessments', null=True, blank=True)
    user_profile = models.ForeignKey(UserProfile, on_delete=models.CASCADE, related_name='assessments')
    status = models.CharField(max_length=50, default='PENDING')
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'tenant_member_assessments'
        managed = False
